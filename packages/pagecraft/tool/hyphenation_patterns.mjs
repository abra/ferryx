// Generates pagecraft's hyphenation patterns from hyph-utf8 (the TeX
// hyphenation patterns Android's hyphenator, and with it the WebView
// reader on Android, is built from), at a pinned commit:
//   lib/src/text/hyphenation_patterns_<language>.dart  one part per language
// Each keeps its file's copyright and licence and the language's
// hyphenmins; a new language also needs its notice in LICENSE (the
// hyphenator test checks). Run from packages/pagecraft:
//   node tool/hyphenation_patterns.mjs
import { writeFileSync } from 'node:fs'

const commit = '5684c0f51c0b81133db2efbe60a408b4155a3ff5'
const base = `https://raw.githubusercontent.com/hyphenation/tex-hyphen/${commit}/hyph-utf8/tex/generic/hyph-utf8/patterns`
// hyph-utf8 name → Dart suffix.
const languages = {
  'en-us': 'en_us',
  'en-gb': 'en_gb',
  'ru': 'ru',
  'uk': 'uk',
  'de-1996': 'de',
  'fr': 'fr',
  'es': 'es',
  'it': 'it',
  'pt': 'pt',
}

const get = async url => {
  const response = await fetch(url)
  if (response.status === 404) return ''
  if (!response.ok) throw new Error(`${url}: ${response.status}`)
  return response.text()
}

// The `% copyright:` and `% licence:` block of a .tex header, and its
// hyphenmins.
const header = tex => {
  const lines = tex.split('\n').filter(l => l.startsWith('%')).map(l => l.slice(1))
  const notice = []
  let keep = false
  let left = 2
  let right = 2
  let inMins = false
  for (const line of lines) {
    const key = line.match(/^ ?([a-z]+):/)?.[1]
    if (key) {
      keep = key === 'copyright' || key === 'licence'
      inMins = key === 'hyphenmins'
    }
    if (inMins) {
      const l = line.match(/left:\s*(\d+)/)
      const r = line.match(/right:\s*(\d+)/)
      if (l) left = Number(l[1])
      if (r) right = Number(r[1])
    }
    if (keep) notice.push(line.trimEnd())
  }
  return { notice, left, right }
}

const wrap = words => {
  const out = []
  let line = ''
  for (const word of words) {
    if (line.length + word.length + 1 > 76) {
      out.push(line)
      line = word
    } else {
      line = line ? `${line} ${word}` : word
    }
  }
  if (line) out.push(line)
  return out.join('\n')
}

const camel = name => name.replace(/_(.)/g, (_, c) => c.toUpperCase())

for (const [name, suffix] of Object.entries(languages)) {
  const tex = await get(`${base}/tex/hyph-${name}.tex`)
  const patterns = (await get(`${base}/txt/hyph-${name}.pat.txt`))
    .split(/\s+/).filter(Boolean)
  const exceptions = (await get(`${base}/txt/hyph-${name}.hyp.txt`))
    .split(/\s+/).filter(Boolean)
  const { notice, left, right } = header(tex)
  const text = [...patterns, ...exceptions].join(' ')
  if (text.includes("'''")) throw new Error(`${name}: triple quote`)
  const dart = `// GENERATED by tool/hyphenation_patterns.mjs from hyph-utf8 (tex-hyphen
// ${commit}), hyph-${name}. Do not edit.
//
${notice.map(l => `//${l}`).join('\n')}

part of 'hyphenation_patterns.dart';

const _${camel(suffix)} = HyphenationPatterns(
  left: ${left},
  right: ${right},
  patterns: r'''
${wrap(patterns)}
''',
  exceptions: r'''
${wrap(exceptions)}
''',
);
`
  writeFileSync(`lib/src/text/hyphenation_patterns_${suffix}.dart`, dart)
  console.log(`${name}: ${patterns.length} patterns, ${exceptions.length} exceptions, mins ${left}/${right}`)
}
