// Generates what pagecraft needs to fold text for search exactly as the
// WebView reader's search.js does (toLocaleLowerCase, ς → σ, NFD,
// combining marks dropped). Dart has no String.normalize, and its case
// tables and \p{M} follow an older Unicode than ICU, so both come from
// here:
//   lib/src/search/search_fold_table.dart  marks and per-character folds
//   test/fixtures/search_fold.json         JS's fold of every changed code point
// Run from packages/pagecraft: node tool/search_fold_table.mjs
import { writeFileSync } from 'node:fs'

const isMark = s => /^\p{M}$/u.test(s)
const isHangul = cp => cp >= 0xAC00 && cp <= 0xD7A3
const fold = s => s.toLocaleLowerCase('en').replace(/ς/g, 'σ')
  .normalize('NFD').replace(/\p{M}/gu, '')
const markRanges = []
const keys = []
const values = []
const sequences = []
for (let cp = 0; cp <= 0x10FFFF; cp++) {
  if (cp >= 0xD800 && cp <= 0xDFFF) continue
  const s = String.fromCodePoint(cp)
  if (isMark(s)) {
    const last = markRanges[markRanges.length - 1]
    if (last && last[1] === cp - 1) last[1] = cp
    else markRanges.push([cp, cp])
    continue
  }
  if (cp < 0x80 || isHangul(cp)) continue
  const f = fold(s)
  if (f === s) continue
  const points = [...f].map(c => c.codePointAt(0))
  keys.push(cp)
  if (points.length === 1) values.push(points[0])
  else { values.push(-1); sequences.push([cp, points]) }
}
const hex = v => v < 0 ? '-1' : `0x${v.toString(16)}`
const rows = (list, perLine) => {
  const out = []
  for (let i = 0; i < list.length; i += perLine)
    out.push('  ' + list.slice(i, i + perLine).map(hex).join(', ') + ',')
  return out.join('\n')
}
writeFileSync('lib/src/search/search_fold_table.dart', `// Generated by tool/search_fold_table.mjs (node ${process.versions.node},
// ICU ${process.versions.icu}, Unicode ${process.versions.unicode}); do not edit.
part of 'text_node_search.dart';

/// Combining marks (\\p{M}) as inclusive ranges, flattened and sorted.
const _markRanges = <int>[
${rows(markRanges.flat(), 10)}
];

/// Non-ASCII code points the search fold changes, sorted; Hangul
/// syllables are decomposed by the code.
const _foldKeys = <int>[
${rows(keys, 10)}
];

/// Each key's fold as one code point, or -1 when [_foldSequences] has it.
const _foldValues = <int>[
${rows(values, 10)}
];

/// Folds that are not one code point (none, or several).
const _foldSequences = <int, List<int>>{
${sequences.map(([k, v]) => `  ${hex(k)}: [${v.map(hex).join(', ')}],`).join('\n')}
};
`)

const changed = {}
for (let cp = 0x80; cp <= 0x10FFFF; cp++) {
  if (cp >= 0xD800 && cp <= 0xDFFF) continue
  if (isHangul(cp) && (cp - 0xAC00) % 97 !== 0) continue
  const s = String.fromCodePoint(cp)
  const f = fold(s)
  if (f !== s) changed[cp] = f
}
writeFileSync('test/fixtures/search_fold.json', JSON.stringify({
  unicode: process.versions.unicode, changed,
}))
console.log('marks', markRanges.length, 'keys', keys.length, 'sequences', sequences.length, 'changed', Object.keys(changed).length)
